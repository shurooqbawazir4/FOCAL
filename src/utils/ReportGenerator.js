/**
 * Professional PDF Report Generator for FOCAL Admin Dashboard
 * 
 * This utility generates comprehensive PDF reports containing dashboard analytics,
 * charts, and statistical data with professional formatting and university branding.
 */

import jsPDF from 'jspdf';
import html2canvas from 'html2canvas';

class ReportGenerator {
  constructor() {
    this.doc = new jsPDF('p', 'mm', 'a4');
    this.pageWidth = this.doc.internal.pageSize.getWidth();
    this.pageHeight = this.doc.internal.pageSize.getHeight();
    this.margin = 20;
    this.currentY = this.margin;
    this.lineHeight = 7;
    this.sectionSpacing = 15;
  }

  /**
   * Generate a comprehensive dashboard report
   * @param {Object} reportData - Dashboard data and charts
   * @param {Object} userInfo - Admin user information
   * @param {Object} filters - Applied filters (course, date range, etc.)
   */
  async generateDashboardReport(reportData, userInfo, filters) {
    try {
      // Reset document
      this.doc = new jsPDF('p', 'mm', 'a4');
      this.currentY = this.margin;

      // Add header with university branding
      await this.addHeader(userInfo);
      
      // Add executive summary
      this.addExecutiveSummary(reportData.stats, filters);
      
      // Add statistics overview
      this.addStatisticsOverview(reportData.stats);
      
      // Add charts section
      if (reportData.charts) {
        await this.addChartsSection(reportData.charts, filters);
      }
      
      // Add detailed analytics
      this.addDetailedAnalytics(reportData);
      
      // Add footer
      this.addFooter();
      
      // Generate filename
      const timestamp = new Date().toISOString().split('T')[0];
      const filename = `FOCAL_Dashboard_Report_${timestamp}.pdf`;
      
      // Save the PDF
      this.doc.save(filename);
      
      return { success: true, filename };
    } catch (error) {
      console.error('Error generating report:', error);
      return { success: false, error: error.message };
    }
  }

  /**
   * Add professional header with university branding
   */
  async addHeader(userInfo) {
    // University name and logo area
    this.doc.setFontSize(20);
    this.doc.setFont('helvetica', 'bold');
    this.doc.text('Prince Sultan University', this.margin, this.currentY);
    
    this.currentY += 8;
    this.doc.setFontSize(14);
    this.doc.setFont('helvetica', 'normal');
    this.doc.text('Department of Computer Science', this.margin, this.currentY);
    
    this.currentY += 6;
    this.doc.setFontSize(12);
    this.doc.text('FOCAL - Attention Monitoring System', this.margin, this.currentY);
    
    // Add logo placeholder (you can replace this with actual logo)
    this.addLogoPlaceholder();
    
    // Report title
    this.currentY += 20;
    this.doc.setFontSize(18);
    this.doc.setFont('helvetica', 'bold');
    this.doc.text('Dashboard Analytics Report', this.margin, this.currentY);
    
    // Report metadata
    this.currentY += 10;
    this.doc.setFontSize(10);
    this.doc.setFont('helvetica', 'normal');
    this.doc.text(`Generated on: ${new Date().toLocaleDateString()}`, this.margin, this.currentY);
    this.doc.text(`Generated by: ${userInfo?.firstName || 'Admin'} ${userInfo?.lastName || ''}`, this.margin + 80, this.currentY);
    
    this.currentY += 6;
    this.doc.text(`Department: ${userInfo?.department || 'Computer Science'}`, this.margin, this.currentY);
    
    // Add horizontal line
    this.currentY += 8;
    this.doc.setLineWidth(0.5);
    this.doc.line(this.margin, this.currentY, this.pageWidth - this.margin, this.currentY);
    this.currentY += 5;
  }

  /**
   * Add university logo to the report
   */
  async addLogoPlaceholder() {
    try {
      // Load the actual PSU logo
      const logoUrl = '/images/psu-logo.png';
      const logoData = await this.loadImageAsBase64(logoUrl);
      
      // Add the logo to the PDF
      this.doc.addImage(logoData, 'PNG', this.pageWidth - 60, this.margin, 40, 30);
      
      console.log('PSU logo loaded successfully');
    } catch (error) {
      console.warn('Could not load university logo:', error);
      // Fallback to placeholder
      this.doc.setFillColor(240, 240, 240);
      this.doc.rect(this.pageWidth - 60, this.margin, 40, 30, 'F');
      this.doc.setFontSize(8);
      this.doc.setFont('helvetica', 'normal');
      this.doc.text('PSU Logo', this.pageWidth - 50, this.margin + 20);
      
      // Add border around logo area
      this.doc.setDrawColor(200, 200, 200);
      this.doc.setLineWidth(0.5);
      this.doc.rect(this.pageWidth - 60, this.margin, 40, 30);
    }
  }

  /**
   * Helper method to load image as base64 for embedding in PDF
   */
  async loadImageAsBase64(url) {
    return new Promise((resolve, reject) => {
      const img = new Image();
      img.crossOrigin = 'anonymous';
      img.onload = () => {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        canvas.width = img.width;
        canvas.height = img.height;
        ctx.drawImage(img, 0, 0);
        resolve(canvas.toDataURL('image/png'));
      };
      img.onerror = reject;
      img.src = url;
    });
  }

  /**
   * Add executive summary section
   */
  addExecutiveSummary(stats, filters) {
    this.addSectionTitle('Executive Summary');
    
    let summaryText = `This report provides a comprehensive analysis of the attention monitoring system `;
    
    if (filters && filters.generated && filters.course && filters.course !== 'All Courses') {
      summaryText += `for ${filters.course} during the selected period. The analysis includes detailed attention `;
      summaryText += `trends, section comparisons, and performance insights for the specified course and timeframe.`;
    } else {
      summaryText += `across the department. The dashboard shows key performance indicators including instructor `;
      summaryText += `engagement, course performance, and overall attention metrics.`;
    }
    
    this.addWrappedText(summaryText, 12);
    this.currentY += 5;
    
    // Add filter information
    if (filters) {
      this.doc.setFontSize(10);
      this.doc.setFont('helvetica', 'bold');
      this.doc.text('Report Scope & Filters:', this.margin, this.currentY);
      this.currentY += 5;
      
      this.doc.setFont('helvetica', 'normal');
      if (filters.course) {
        this.doc.text(`• Course: ${filters.course}`, this.margin + 5, this.currentY);
        this.currentY += 4;
      }
      if (filters.dateFrom && filters.dateTo) {
        this.doc.text(`• Date Range: ${filters.dateFrom} to ${filters.dateTo}`, this.margin + 5, this.currentY);
        this.currentY += 4;
      } else if (filters.generated) {
        this.doc.text(`• Date Range: Not specified (using all available data)`, this.margin + 5, this.currentY);
        this.currentY += 4;
      }
      if (filters.selectedSections && filters.selectedSections.length > 0) {
        this.doc.text(`• Sections: ${filters.selectedSections.join(', ')}`, this.margin + 5, this.currentY);
        this.currentY += 4;
      } else if (filters.generated) {
        this.doc.text(`• Sections: All available sections`, this.margin + 5, this.currentY);
        this.currentY += 4;
      }
      if (filters.generated) {
        this.doc.text(`• Analysis Type: Detailed analytics with chart data`, this.margin + 5, this.currentY);
        this.currentY += 4;
      } else {
        this.doc.text(`• Analysis Type: Overview statistics`, this.margin + 5, this.currentY);
        this.currentY += 4;
      }
    }
    
    this.currentY += this.sectionSpacing;
  }

  /**
   * Add statistics overview section
   */
  addStatisticsOverview(stats) {
    this.addSectionTitle('Key Performance Indicators');
    
    // Create a table for statistics
    const tableData = [
      ['Metric', 'Value', 'Description'],
      ['Total Instructors', stats.instructors || 0, 'Number of active instructors in the system'],
      ['Total Courses', stats.courses || 0, 'Number of courses being monitored'],
      ['Total Classes', stats.classes || 0, 'Number of class sessions conducted'],
      ['Average Attention', `${Math.round(stats.avgAttention || 0)}%`, 'Overall attention rate across all sessions']
    ];
    
    this.addTable(tableData);
    this.currentY += this.sectionSpacing;
  }

  /**
   * Add charts section with descriptions
   */
  async addChartsSection(charts, filters) {
    this.addSectionTitle('Analytical Charts & Visualizations');
    
    // Add chart descriptions
    this.doc.setFontSize(11);
    this.doc.setFont('helvetica', 'normal');
    
    if (charts.bestCourses) {
      this.doc.setFontSize(12);
      this.doc.setFont('helvetica', 'bold');
      this.doc.text('1. Best Performing Courses Analysis', this.margin, this.currentY);
      this.currentY += 6;
      
      this.doc.setFontSize(10);
      this.doc.setFont('helvetica', 'normal');
      this.addWrappedText('This bar chart displays the top 5 courses with the highest average attention rates across the department. The chart helps identify which courses are most engaging and successful in maintaining student attention throughout the semester.', 10);
      this.currentY += 5;
      
      // Add insights from the chart data
      if (charts.bestCourses.labels && charts.bestCourses.labels.length > 0) {
        this.doc.setFontSize(9);
        this.doc.setFont('helvetica', 'bold');
        this.doc.text('Key Insights:', this.margin + 5, this.currentY);
        this.currentY += 4;
        
        this.doc.setFont('helvetica', 'normal');
        const topCourse = charts.bestCourses.labels[0];
        const topScore = charts.bestCourses.datasets[0]?.data[0];
        this.addWrappedText(`• Top performing course: ${topCourse} with ${topScore}% average attention`, 9);
        this.currentY += 3;
        this.addWrappedText(`• This analysis helps identify successful teaching methodologies that can be shared across the department`, 9);
        this.currentY += 8;
      }
    }
    
    if (charts.attentionAnalytics) {
      this.doc.setFontSize(12);
      this.doc.setFont('helvetica', 'bold');
      this.doc.text('2. Attention Analytics Over Time', this.margin, this.currentY);
      this.currentY += 6;
      
      this.doc.setFontSize(10);
      this.doc.setFont('helvetica', 'normal');
      
      if (filters && filters.course && filters.course !== 'All Courses') {
        this.addWrappedText(`This chart shows the attention trends over time for ${filters.course}. The visualization provides insights into attention patterns and helps identify peak and low attention periods throughout the selected timeframe.`, 10);
      } else {
        this.addWrappedText('This chart shows the attention trends over time for the selected course and sections. The visualization provides insights into attention patterns and helps identify peak and low attention periods throughout the selected timeframe.', 10);
      }
      this.currentY += 5;
      
      // Add chart type description
      if (charts.attentionAnalytics.datasets && charts.attentionAnalytics.datasets.length > 1) {
        this.doc.setFontSize(9);
        this.doc.setFont('helvetica', 'bold');
        this.doc.text('Chart Type: Multi-Section Comparison (Bar Chart)', this.margin + 5, this.currentY);
        this.currentY += 4;
        this.doc.setFont('helvetica', 'normal');
        this.addWrappedText('This bar chart compares attention rates across multiple sections, allowing for direct comparison of performance between different class sections.', 9);
      } else {
        this.doc.setFontSize(9);
        this.doc.setFont('helvetica', 'bold');
        this.doc.text('Chart Type: Time Series Analysis (Line Chart)', this.margin + 5, this.currentY);
        this.currentY += 4;
        this.doc.setFont('helvetica', 'normal');
        this.addWrappedText('This line chart shows attention trends over time, making it easy to identify patterns, trends, and any significant changes in student engagement.', 9);
      }
      this.currentY += 8;
    }
    
    // Add methodology note
    this.doc.setFontSize(9);
    this.doc.setFont('helvetica', 'italic');
    this.doc.setFillColor(248, 249, 250);
    this.doc.rect(this.margin, this.currentY, this.pageWidth - (2 * this.margin), 15, 'F');
    this.doc.setFont('helvetica', 'bold');
    this.doc.text('Methodology Note:', this.margin + 2, this.currentY + 4);
    this.doc.setFont('helvetica', 'normal');
    this.doc.text('Attention rates are calculated based on real-time monitoring data collected during class sessions.', this.margin + 2, this.currentY + 8);
    this.currentY += 20;
    
    this.currentY += this.sectionSpacing;
  }

  /**
   * Add detailed analytics section
   */
  addDetailedAnalytics(reportData) {
    this.addSectionTitle('Detailed Analytics');
    
    // Course performance analysis
    if (reportData.courses && reportData.courses.length > 0) {
      this.doc.setFontSize(12);
      this.doc.setFont('helvetica', 'bold');
      this.doc.text('Course Performance Analysis:', this.margin, this.currentY);
      this.currentY += 6;
      
      // Top performing courses
      const topCourses = reportData.courses
        .filter(c => typeof c.avgAttention === 'number')
        .sort((a, b) => b.avgAttention - a.avgAttention)
        .slice(0, 5);
      
      if (topCourses.length > 0) {
        this.doc.setFontSize(10);
        this.doc.setFont('helvetica', 'normal');
        this.doc.text('Top 5 Performing Courses:', this.margin + 5, this.currentY);
        this.currentY += 4;
        
        topCourses.forEach((course, index) => {
          const courseName = `${course.course_code || course.code || 'CRS'} - ${course.course_name || course.name || 'Unknown'}`;
          this.doc.text(`${index + 1}. ${courseName}: ${Math.round(course.avgAttention)}%`, this.margin + 10, this.currentY);
          this.currentY += 4;
        });
      }
    }
    
    this.currentY += 8;
    
    // Recommendations section
    this.addRecommendations(reportData);
  }

  /**
   * Add recommendations based on data
   */
  addRecommendations(reportData) {
    this.doc.setFontSize(12);
    this.doc.setFont('helvetica', 'bold');
    this.doc.text('Recommendations:', this.margin, this.currentY);
    this.currentY += 6;
    
    this.doc.setFontSize(10);
    this.doc.setFont('helvetica', 'normal');
    
    const recommendations = [
      '• Monitor courses with attention rates below 70% and implement engagement strategies',
      '• Share best practices from top-performing courses with other instructors',
      '• Schedule regular review sessions to analyze attention patterns and trends',
      '• Consider implementing interactive elements in courses with declining attention',
      '• Provide additional training for instructors teaching courses with low attention rates'
    ];
    
    recommendations.forEach(rec => {
      this.addWrappedText(rec, 10);
      this.currentY += 4;
    });
    
    this.currentY += this.sectionSpacing;
  }

  /**
   * Add professional footer
   */
  addFooter() {
    const footerY = this.pageHeight - 20;
    
    // Add horizontal line
    this.doc.setLineWidth(0.3);
    this.doc.line(this.margin, footerY - 5, this.pageWidth - this.margin, footerY - 5);
    
    // Footer text
    this.doc.setFontSize(8);
    this.doc.setFont('helvetica', 'normal');
    this.doc.text('FOCAL - Attention Monitoring System | Prince Sultan University', this.margin, footerY);
    this.doc.text(`Page 1 of 1 | Generated on ${new Date().toLocaleString()}`, this.pageWidth - 60, footerY);
  }

  /**
   * Add section title with proper formatting
   */
  addSectionTitle(title) {
    this.currentY += 5;
    this.doc.setFontSize(14);
    this.doc.setFont('helvetica', 'bold');
    this.doc.text(title, this.margin, this.currentY);
    this.currentY += 8;
  }

  /**
   * Add wrapped text with proper line breaks
   */
  addWrappedText(text, fontSize = 10) {
    this.doc.setFontSize(fontSize);
    this.doc.setFont('helvetica', 'normal');
    
    const maxWidth = this.pageWidth - (2 * this.margin);
    const lines = this.doc.splitTextToSize(text, maxWidth);
    
    lines.forEach(line => {
      if (this.currentY > this.pageHeight - 30) {
        this.doc.addPage();
        this.currentY = this.margin;
      }
      this.doc.text(line, this.margin, this.currentY);
      this.currentY += this.lineHeight;
    });
  }

  /**
   * Add a table with proper formatting
   */
  addTable(data) {
    const tableWidth = this.pageWidth - (2 * this.margin);
    const colWidth = tableWidth / data[0].length;
    const rowHeight = 8;
    
    // Draw table
    data.forEach((row, rowIndex) => {
      const y = this.currentY + (rowIndex * rowHeight);
      
      row.forEach((cell, colIndex) => {
        const x = this.margin + (colIndex * colWidth);
        
        // Draw cell border
        this.doc.rect(x, y - rowHeight + 2, colWidth, rowHeight);
        
        // Add cell content
        this.doc.setFontSize(9);
        this.doc.setFont('helvetica', rowIndex === 0 ? 'bold' : 'normal');
        this.doc.text(cell.toString(), x + 2, y - 2);
      });
    });
    
    this.currentY += (data.length * rowHeight) + 5;
  }
}

export default ReportGenerator;
